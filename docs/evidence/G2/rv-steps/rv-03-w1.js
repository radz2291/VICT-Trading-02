const $ = (s) => document.querySelector(s);
const txt = (s) => ($(s) ? $(s).textContent.replace(/\s+/g,' ').trim() : null);
const out = {};
const btn = $('[data-testid="btn-add-level"]');
if (!btn) return { error: 'no add-level button' };
btn.click();
await new Promise((r) => setTimeout(r, 400));
const priceField = $('[data-testid="edit-price"]');
if (!priceField) return { error: 'no edit-price after create' };
priceField.value = '2649.50';
priceField.dispatchEvent(new Event('input', { bubbles: true }));
priceField.dispatchEvent(new Event('change', { bubbles: true }));
await new Promise((r) => setTimeout(r, 500));
out.afterEdit = { status: txt('[data-testid="mutation-status"]'), store: (localStorage.getItem('g1.levels.v1') || '').slice(0, 140) };
$('[data-testid="btn-undo"]').click();
await new Promise((r) => setTimeout(r, 500));
out.afterUndo = { status: txt('[data-testid="mutation-status"]') };
$('[data-testid="btn-redo"]').click();
await new Promise((r) => setTimeout(r, 500));
out.afterRedo = { status: txt('[data-testid="mutation-status"]'), levels: [...document.querySelectorAll('[data-testid="panel-drawings"] li')].length, g2present: !!localStorage.getItem('g2.replay.v1') };
out.PASS = String(out.afterEdit.status).includes('saved') && String(out.afterUndo.status).includes('saved') && String(out.afterRedo.status).includes('saved');
return out;
